#!/usr/bin/env node
/**
 * CLI-001：OpenAPI 快照 → apps/cli/internal/services/apidef/paths.go（Go 路径常量）。
 * 门禁 4 的 Go 侧等价物：服务命令禁止手写接口路径，一律引用本生成物。
 * 用法：node scripts/gen-cli-services.mjs [--check]（--check：与磁盘不一致时退出 1，CI 校验）
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SNAPSHOT = path.join(ROOT, "packages/api-client/src/generated/openapi.json");
const OUT = path.join(ROOT, "apps/cli/internal/services/apidef/paths.go");

/** CLI P1 暴露面（method → path，OpenAPI 模板参数原样保留 {x}） */
const CLI_EXPOSED = [
  ["GET", "/api/v1/personal/projects"],
  ["GET", "/api/v1/personal/me"],
  ["GET", "/api/v1/projects/{projectId}/cases"],
  ["POST", "/api/v1/projects/{projectId}/cases"],
  ["GET", "/api/v1/projects/{projectId}/cases/{caseId}"],
  ["PUT", "/api/v1/projects/{projectId}/cases/{caseId}"],
  ["DELETE", "/api/v1/projects/{projectId}/cases/{caseId}"],
  ["GET", "/api/v1/projects/{projectId}/apis"],
  ["GET", "/api/v1/projects/{projectId}/apis/{apiId}/cases"],
  ["POST", "/api/v1/projects/{projectId}/apis/{apiId}/cases/execute"],
  ["GET", "/api/v1/projects/{projectId}/environments"],
  ["GET", "/api/v1/projects/{projectId}/scenarios"],
  ["POST", "/api/v1/projects/{projectId}/scenarios/{id}/execute"],
  ["GET", "/api/v1/projects/{projectId}/plans"],
  ["GET", "/api/v1/projects/{projectId}/plans/{planId}"],
  ["POST", "/api/v1/projects/{projectId}/plans/{planId}/execute"],
  ["GET", "/api/v1/projects/{projectId}/exec-tasks"],
  ["POST", "/api/v1/projects/{projectId}/exec-tasks/{taskId}/stop"],
  ["GET", "/api/v1/open/exec/{taskId}"],
  ["GET", "/api/v1/open/exec/{taskId}/report"],
];

const spec = JSON.parse(readFileSync(SNAPSHOT, "utf8"));
const paths = spec.paths ?? {};

const missing = CLI_EXPOSED.filter(([m, p]) => !paths[p]?.[m.toLowerCase()]);
if (missing.length > 0) {
  console.error(
    "[gen-cli-services] OpenAPI 快照缺少以下 CLI 暴露端点（先运行 node scripts/gen-openapi.mjs）：",
  );
  for (const [m, p] of missing) console.error(`  ${m} ${p}`);
  process.exit(1);
}

const constName = ([m, p]) =>
  m +
  "_" +
  p
    .replace(/^\/api\/v1\//, "")
    .replace(/\{(\w+)\}/g, "_$1_")
    .replace(/[^A-Za-z0-9]/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_|_$/g, "");

const goConsts = CLI_EXPOSED.map(
  ([m, p]) => `\t${constName([m, p])} = "${p}" // ${m}`,
).join("\n");

const go = `// Code generated by scripts/gen-cli-services.mjs from packages/api-client/src/generated/openapi.json.
// 门禁 4（Go 侧）：服务命令禁止手写接口路径——一律引用本文件常量；改动端点先改 OpenAPI 快照再重新生成。
// CLI-001 §4：--check 模式供 CI 校验 diff（对齐 gen-openapi --check 口径）。
package apidef

const (
${goConsts}
)
`;

if (process.argv.includes("--check")) {
  if (!existsSync(OUT)) {
    console.error("[gen-cli-services] paths.go 不存在：运行 node scripts/gen-cli-services.mjs 生成");
    process.exit(1);
  }
  const onDisk = readFileSync(OUT, "utf8");
  if (onDisk !== go) {
    console.error("[gen-cli-services] paths.go 与 OpenAPI 快照不一致：重新生成并提交");
    process.exit(1);
  }
  console.log("[gen-cli-services] check ok");
} else {
  execSync(`mkdir -p ${path.dirname(OUT)}`);
  writeFileSync(OUT, go);
  console.log(`[gen-cli-services] 写入 ${path.relative(ROOT, OUT)}（${CLI_EXPOSED.length} 端点）`);
}
